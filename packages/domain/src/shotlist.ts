import { outputFor } from './handoff.js';
import { formatRange } from './frames.js';
import { planFor, queueRows, type Project, type QueueFilter } from './project.js';
import { SHOT_STATUS_LABELS } from './status.js';
import { PREP_TASKS } from './tasks.js';

/**
 * The printable DIT / VFX prep shot list (master spec §3). Columns follow the
 * spec's table: Shot, Scene/Setup, Frames, Required Prep, Notes, Status,
 * Approval — plus empty check boxes so the list can be marked up on paper.
 */

export interface ShotListRow {
  shot: string;
  sceneSetup: string;
  frames: string;
  requiredPrep: string;
  notes: string;
  status: string;
  approval: string;
  circled: boolean;
}

export function shotListRows(p: Project, filter: QueueFilter = {}): ShotListRow[] {
  return queueRows(p, filter).map(({ shot, state, status }) => {
    const out = outputFor(p.handoff, shot);
    const plan = planFor(p, shot);
    const prep = state.tasks.map((t) => (t.kind === 'sequence_conversion' ? out.format.toUpperCase() : PREP_TASKS[t.kind].short));
    return {
      shot: state.vfxShotId ?? shot.shotId,
      sceneSetup: [shot.scene, shot.setup ? `Setup ${shot.setup}` : null].filter(Boolean).join(' / '),
      // Unknown until the clip is read (a VCDIT handoff carries no range).
      frames: plan ? formatRange(plan.deliveredIn, plan.deliveredOut) : '—',
      requiredPrep: prep.join(' + ') || '—',
      notes: [shot.supervisorNotes, state.notes].filter(Boolean).join(' — '),
      status: SHOT_STATUS_LABELS[status],
      approval: state.approval ? `Approved — ${state.approval.by}` : '—',
      circled: shot.circled,
    };
  });
}

const escapeHtml = (s: string): string =>
  s.replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]!);

/** A complete, self-contained HTML document ready to print or save as PDF. */
export function shotListHtml(p: Project, generatedAt: Date, filter: QueueFilter = {}): string {
  const rows = shotListRows(p, filter);
  const h = p.handoff;
  const day = h.origin?.day;
  const meta = [
    h.productionCompany,
    day?.number !== undefined ? `Shoot day ${day.number}${day.date ? ` (${day.date})` : ''}` : null,
    h.vfxSupervisor ? `VFX Supervisor: ${h.vfxSupervisor}` : null,
    h.ditOperator ? `DIT: ${h.ditOperator}` : null,
    `${rows.length} shot${rows.length === 1 ? '' : 's'}`,
    `Printed ${generatedAt.toISOString().slice(0, 16).replace('T', ' ')} UTC`,
  ].filter((m): m is string => Boolean(m));
  const body = rows
    .map(
      (r) => `<tr>
<td class="shot">${escapeHtml(r.shot)}${r.circled ? ' <span class="circ" title="Circle take">●</span>' : ''}</td>
<td class="nw">${escapeHtml(r.sceneSetup)}</td>
<td class="num">${escapeHtml(r.frames)}</td>
<td>${escapeHtml(r.requiredPrep)}</td>
<td class="notes">${escapeHtml(r.notes)}</td>
<td class="nw">${escapeHtml(r.status)}</td>
<td>${escapeHtml(r.approval)}</td>
<td class="box"></td>
</tr>`,
    )
    .join('\n');
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>${escapeHtml(h.project)} — VFX Prep Shot List</title>
<style>
@page { size: landscape; margin: 12mm; }
body { font: 10pt/1.35 -apple-system, "Segoe UI", Helvetica, Arial, sans-serif; color: #111; margin: 0; }
h1 { font-size: 15pt; margin: 0 0 2pt; }
.meta { color: #555; margin-bottom: 10pt; }
table { width: 100%; border-collapse: collapse; }
th, td { border: 0.6pt solid #999; padding: 4pt 5pt; text-align: left; vertical-align: top; }
th { background: #eee; font-size: 8.5pt; text-transform: uppercase; letter-spacing: .04em; }
tr { page-break-inside: avoid; }
.num { white-space: nowrap; font-variant-numeric: tabular-nums; }
.shot { font-weight: 600; white-space: nowrap; }
.nw { white-space: nowrap; }
.notes { width: 28%; }
.box { width: 14mm; }
.circ { color: #b00; font-size: 8pt; }
footer { margin-top: 10pt; color: #777; font-size: 8pt; }
</style></head><body>
<h1>${escapeHtml(h.project)} — VFX Prep Shot List</h1>
<div class="meta">${meta.map(escapeHtml).join(' · ')}</div>
<table>
<thead><tr><th>Shot</th><th>Scene / Setup</th><th>Frames</th><th>Required Prep</th><th>Notes</th><th>Status</th><th>Approval</th><th>✓</th></tr></thead>
<tbody>
${body}
</tbody></table>
<footer>Frames are delivered numbering including handles (— : not yet read from the clip). ● marks a circle take. Generated by VC VFX.</footer>
</body></html>
`;
}
