export type CameraCategory = 'cinema' | 'mirrorless' | 'broadcast' | 'drone' | 'gimbal' | 'action' | 'phone' | 'other';

export interface CameraModeData {
  id: string;
  name: string;
  /** Active image area, millimetres [width, height]. */
  mm: [number, number];
  /** Recorded raster, pixels [width, height]. */
  px: [number, number];
  verified: boolean;
  aliases?: string[];
  /** Set where the recorded raster itself is anamorphic (squeezed or desqueezed). */
  squeeze?: number;
  notes?: string;
}

export interface CameraBodyData {
  id: string;
  make: string;
  model: string;
  category: CameraCategory;
  sensorFormat: string;
  aliases: string[];
  defaultModeId: string;
  verified: boolean;
  verifiedNotes: string;
  source: string;
  sources: string[];
  /** 35 mm-equivalent focal length as published (fixed-lens cameras). */
  equivFocalMm?: number;
  /** Real focal length of a fixed lens (usually derived from the equivalent; see fixedFocalNotes). */
  fixedFocalMm?: number;
  fixedFocalNotes?: string;
  modes: CameraModeData[];
}

